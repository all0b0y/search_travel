"""Coverage report: `python -m data_build.report` prints it and writes data_build/REPORT.md."""
from __future__ import annotations

import json
import sqlite3
import statistics
import sys
from pathlib import Path

from .common import CACHE_DIR, CATALOG_DB, OPENDATA_DB, ROOT

REPORT = ROOT / "data_build" / "REPORT.md"


def _mb(p: Path) -> str:
    return f"{p.stat().st_size / 1e6:.1f} MB" if p.exists() else "missing"


def _meta(con, prefix):
    return {k[len(prefix):]: json.loads(v) for k, v in con.execute("SELECT key, value FROM meta WHERE key LIKE ?",
                                                                    (prefix + "%",))}


def build_report(opendata=OPENDATA_DB, catalog=CATALOG_DB) -> str:
    from .destinations import BY_ID
    o = sqlite3.connect(opendata)
    c = sqlite3.connect(catalog)
    L = ["# Data build report", "", "Generated by `python -m data_build.report`. Real: places, coordinates, hotel names/kinds,",
         "districts, climate, airports, routes. Synthetic: stars (when not tagged in OSM), ratings, reviews, rooms,",
         "prices, policies, insights events.", ""]
    dests = o.execute("SELECT id, tags, timezone, aliases FROM destinations ORDER BY id").fetchall()
    ids = [d[0] for d in dests]
    n_dest = len(ids)
    clim_ok = {r[0] for r in o.execute("SELECT destination_id FROM climate WHERE air_max_c IS NOT NULL "
                                       "GROUP BY destination_id HAVING COUNT(*) = 12")}
    sea_ok = {r[0] for r in o.execute("SELECT DISTINCT destination_id FROM climate WHERE sea_c IS NOT NULL")}
    coastal = [i for i in ids if (BY_ID[i].is_coastal if i in BY_ID else False)]
    hotels_per = dict(c.execute("SELECT destination_id, COUNT(*) FROM hotels GROUP BY destination_id").fetchall())
    counts = sorted(hotels_per.values())
    dsrc = dict(o.execute("SELECT source, COUNT(*) FROM districts GROUP BY source").fetchall())
    hsrc = dict(c.execute("SELECT source, COUNT(*) FROM hotels GROUP BY source").fetchall())
    n_hotels = c.execute("SELECT COUNT(*) FROM hotels").fetchone()[0]
    rated = c.execute("SELECT COUNT(*) FROM hotels WHERE rating IS NOT NULL").fetchone()[0]
    real_stars = c.execute("SELECT COUNT(*) FROM hotels WHERE stars IS NOT NULL AND synthetic_fields NOT LIKE '%\"stars\"%'"
                           " AND rating IS NOT NULL").fetchone()[0]
    rooms = c.execute("SELECT COUNT(*) FROM rooms").fetchone()[0]
    pols = c.execute("SELECT COUNT(*) FROM policies").fetchone()[0]
    extras = c.execute("SELECT COUNT(*) FROM meta WHERE key LIKE 'hotel_extras:%'").fetchone()[0]
    ev = c.execute("SELECT COUNT(*) FROM insights_events").fetchone()[0]
    groups = c.execute("SELECT MIN(n), MAX(n), COUNT(*) FROM (SELECT COUNT(*) n FROM insights_events "
                       "GROUP BY origin_city, segment, month)").fetchone()
    tz_filled = sum(1 for d in dests if d[2])
    aliased = sum(1 for d in dests if d[3] and d[3] != "[]")
    L += ["## Coverage", "", "| item | value |", "|---|---|",
          f"| destinations | {n_dest} |",
          f"| with full climate (12 months, air) | {len(clim_ok)} |",
          f"| coastal destinations | {len(coastal)} |",
          f"| with sea temperature | {len(sea_ok)} |",
          f"| with timezone | {tz_filled} |",
          f"| with aliases | {aliased} |",
          f"| airports | {o.execute('SELECT COUNT(*) FROM airports').fetchone()[0]} |",
          f"| routes (origin, dest, stops) | {o.execute('SELECT COUNT(*) FROM routes').fetchone()[0]} |",
          f"| destinations with hotels | {len(hotels_per)} |",
          f"| hotels total | {n_hotels} (by source: {hsrc}) |",
          f"| hotels per destination min / median / max | "
          + (f"{counts[0]} / {statistics.median(counts):g} / {counts[-1]}" if counts else "- / - / -") + " |",
          f"| districts | {sum(dsrc.values())} (by source: {dsrc}) |",
          f"| synthetic: hotels with rating / rooms / policies / extras | {rated} / {rooms} / {pols} / {extras} |",
          f"| stars from OSM tag (real) | {real_stars} |",
          f"| insights events | {ev} |",
          f"| insights groups origin x segment x month: count, min n, max n | {groups[2]}, {groups[0]}, {groups[1]} |",
          f"| data/opendata.sqlite | {_mb(Path(opendata))} |",
          f"| data/ostrovok_catalog.sqlite | {_mb(Path(catalog))} |", ""]
    missing_h = [i for i in ids if i not in hotels_per]
    L += ["## Gaps and fallbacks", "",
          f"- Destinations without hotels/districts yet ({len(missing_h)}): {', '.join(missing_h) or 'none'}",
          f"- Destinations without full climate ({n_dest - len(clim_ok)}): "
          f"{', '.join(i for i in ids if i not in clim_ok) or 'none'}",
          f"- Coastal destinations without sea temperature: {', '.join(i for i in coastal if i not in sea_ok) or 'none'}"]
    done = _meta(c, "hotels_done:")
    photon = sorted(k for k, v in done.items() if v.get("source") == "photon")
    few = sorted(f"{k} ({v})" for k, v in hotels_per.items() if v < 20)
    dups = sorted(f"{k} ({v.get('skipped_dup')})" for k, v in done.items() if v.get("skipped_dup"))
    L += [f"- Hotels built from the Photon fallback (Overpass down): {', '.join(photon) or 'none'}",
          f"- Destinations with fewer than 20 named hotels in their area: {', '.join(few) or 'none'}",
          f"- Hotels skipped because another destination already holds them (overlapping areas): "
          f"{', '.join(dups) or 'none'}"]
    no_air = [d[0] for d in dests if d[0] in BY_ID and not json.loads(o.execute(
        "SELECT airports FROM destinations WHERE id=?", (d[0],)).fetchone()[0])]
    L += [f"- Destinations with no served airport within 150 km: {', '.join(no_air) or 'none'}"]
    srcs = dict(o.execute("SELECT source, COUNT(*) FROM destinations GROUP BY source").fetchall())
    L += [f"- Destination coordinate sources: {srcs}"]
    # timezone cross-check against Open-Meteo's coordinate-derived zone (cached archive responses)
    mism = []
    for did, _tags, tz, _al in dests:
        f = CACHE_DIR / "open-meteo" / "archive" / f"{did}.json"
        if f.exists() and tz:
            try:
                om = json.loads(f.read_text(encoding="utf-8")).get("timezone")
            except ValueError:
                om = None
            if om and om != tz:
                mism.append(f"{did}: table {tz} vs open-meteo {om}")
    L += [f"- Timezone table vs Open-Meteo zone mismatches: {'; '.join(mism) or 'none'}", ""]
    notes = _meta(o, "climate_done:")
    sea_notes = sorted(f"{k}: {v.get('note')}" for k, v in notes.items() if v.get("note") and "no marine" in v["note"])
    if sea_notes:
        L += ["Marine probing found no SST grid point for: " + "; ".join(sea_notes), ""]
    L += ["## Sources", ""]
    for k, v in o.execute("SELECT key, value FROM meta WHERE key LIKE 'source.%' ORDER BY key"):
        L.append(f"- opendata `{k}`: {v}")
    for k, v in c.execute("SELECT key, value FROM meta WHERE key LIKE 'source.%' ORDER BY key"):
        L.append(f"- catalog `{k}`: {v}")
    L.append("")
    o.close()
    c.close()
    return "\n".join(L)


def main(argv=None) -> int:
    text = build_report()
    print(text)
    REPORT.write_text(text + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
